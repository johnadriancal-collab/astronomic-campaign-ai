"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { AlertTriangle, ArrowLeft, Rocket, Users } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import { Separator } from "@/components/ui/separator";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { FilterBadges } from "@/components/filter-badges";
import { EmailStepCard } from "@/components/email-step-card";
import { StageList, type Stage } from "@/components/stage-list";
import { useCampaignStore } from "@/lib/store";
import { searchProspects, buildCampaign, ApiError } from "@/lib/api";

export default function ResultsPage() {
  const router = useRouter();
  const { campaign, setCampaign } = useCampaignStore();

  const [searchLoading, setSearchLoading] = useState(false);
  const [searchError, setSearchError] = useState<string | null>(null);
  const [buildLoading, setBuildLoading] = useState(false);
  const [buildError, setBuildError] = useState<string | null>(null);
  const [buildStarted, setBuildStarted] = useState(false);

  useEffect(() => {
    if (!campaign) {
      router.replace("/");
    }
  }, [campaign, router]);

  useEffect(() => {
    // Also resumes a campaign left mid-pipeline (status "searching"/"ranking")
    // by an earlier crashed/interrupted attempt -- the backend's pipeline
    // engine picks up at exactly the step that didn't finish, re-running
    // only that one, never redoing a search that already succeeded.
    const resumable = ["draft", "searching", "ranking"];
    if (!campaign || !resumable.includes(campaign.status) || searchLoading) return;
    let cancelled = false;

    (async () => {
      setSearchLoading(true);
      setSearchError(null);
      try {
        // Reuses the campaign_id from preview -- the stored plan is
        // never regenerated here, only searched against.
        const updated = await searchProspects(campaign.campaign_id);
        if (!cancelled) setCampaign(updated);
      } catch (err) {
        if (!cancelled) {
          // No hardcoded "Apollo search failed" prefix -- the backend now
          // attributes the message to whichever step actually failed
          // (search or ranking), so it's already accurate on its own.
          setSearchError(err instanceof ApiError ? err.message : "Couldn't reach the backend to search.");
        }
      } finally {
        if (!cancelled) setSearchLoading(false);
      }
    })();

    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [campaign?.campaign_id, campaign?.status]);

  async function handleBuild() {
    if (!campaign) return;
    setBuildStarted(true);
    setBuildLoading(true);
    setBuildError(null);
    try {
      const updated = await buildCampaign(campaign.campaign_id, false);
      setCampaign(updated);
    } catch (err) {
      setBuildError(
        err instanceof ApiError ? `Apollo build failed (${err.status}): ${err.message}` : "Couldn't reach the backend to build the campaign."
      );
    } finally {
      setBuildLoading(false);
    }
  }

  if (!campaign) return null;

  const searched = campaign.status !== "draft";
  const built = campaign.status === "built" || campaign.status === "failed";

  const stages: Stage[] = [
    { key: "generate", label: "Plan generated by Claude", detail: campaign.plan.campaign_name, status: "done" },
    {
      key: "search",
      label: "Apollo Search",
      detail: searchLoading
        ? "Querying mixed_people/api_search…"
        : searchError
        ? searchError
        : campaign.total_matches !== null
        ? `${campaign.total_matches.toLocaleString()} matches found`
        : undefined,
      status: searchLoading ? "active" : searchError ? "error" : searched ? "done" : "pending",
    },
  ];

  if (searched) {
    stages.push({
      key: "selected",
      label: "Selected",
      detail: `${campaign.selected_prospect_count} highest-ranked prospects`,
      status: "done",
    });
  }

  if (buildStarted) {
    stages.push({
      key: "build",
      label: "Apollo Build",
      detail: buildLoading
        ? "Creating list, sequence, steps, and enrolling contacts…"
        : buildError
        ? buildError
        : built
        ? `${campaign.contacts_created} contacts created · ${campaign.contacts_enrolled} enrolled into sequence`
        : undefined,
      status: buildLoading ? "active" : buildError ? "error" : campaign.status === "built" ? "done" : campaign.status === "failed" ? "error" : "pending",
    });
  }

  return (
    <div className="mx-auto max-w-6xl px-6 py-10">
      <button
        onClick={() => router.push("/")}
        className="mb-6 flex items-center gap-1.5 text-sm text-muted-foreground transition-colors hover:text-foreground"
      >
        <ArrowLeft className="h-3.5 w-3.5" />
        New campaign
      </button>

      <div className="grid gap-8 lg:grid-cols-[1fr_320px]">
        <div className="min-w-0 space-y-8">
          <div className="animate-in fade-in slide-in-from-bottom-2 duration-500">
            <div className="flex flex-wrap items-center gap-3">
              <h1 className="font-serif text-2xl font-medium tracking-tight sm:text-3xl">{campaign.plan.campaign_name}</h1>
              {searchLoading ? (
                <Skeleton className="h-6 w-48 rounded-full" />
              ) : campaign.total_matches !== null ? (
                <>
                  <Badge
                    variant="outline"
                    className="gap-1.5 rounded-full border-border/60 font-normal text-muted-foreground"
                  >
                    <Users className="h-3 w-3" />
                    Apollo Matches: {campaign.total_matches.toLocaleString()}
                  </Badge>
                  <Badge className="gap-1.5 rounded-full bg-primary/15 text-primary hover:bg-primary/15">
                    Selected: {campaign.selected_prospect_count}
                  </Badge>
                </>
              ) : null}
            </div>
            <p className="mt-2 max-w-2xl text-sm text-muted-foreground">{campaign.original_prompt}</p>
          </div>

          <Separator className="bg-border/60" />

          <section>
            <h2 className="mb-4 text-sm font-medium text-muted-foreground">Audience filters</h2>
            <FilterBadges filters={campaign.plan.filters} />
          </section>

          <Separator className="bg-border/60" />

          <section>
            <h2 className="mb-4 text-sm font-medium text-muted-foreground">
              Email sequence · {campaign.plan.sequence.length} steps
            </h2>
            <div className="grid gap-4 sm:grid-cols-2">
              {campaign.plan.sequence.map((step, i) => (
                <EmailStepCard key={`${step.day}-${i}`} step={step} index={i} />
              ))}
            </div>
          </section>
        </div>

        <aside className="lg:sticky lg:top-20 lg:self-start">
          <div className="rounded-2xl border border-border/60 bg-card/60 p-5">
            <h2 className="mb-4 text-sm font-medium">Apollo pipeline</h2>
            <StageList stages={stages} />

            <Separator className="my-5 bg-border/60" />

            {!buildStarted ? (
              <div className="space-y-2">
                <Button
                  onClick={handleBuild}
                  disabled={searchLoading || !!searchError}
                  className="w-full gap-1.5"
                >
                  <Rocket className="h-4 w-4" />
                  Build in Apollo
                </Button>
                <p className="flex items-start gap-1.5 text-xs text-muted-foreground">
                  <AlertTriangle className="mt-0.5 h-3 w-3 shrink-0" />
                  Creates real contacts, a list, and a sequence in your Apollo
                  account. Never sends anything — activation is a separate,
                  explicit step.
                </p>
              </div>
            ) : (
              buildError && (
                <div className="space-y-2">
                  <Alert variant="destructive">
                    <AlertTitle>Build failed</AlertTitle>
                    <AlertDescription>{buildError}</AlertDescription>
                  </Alert>
                  <Button onClick={handleBuild} disabled={buildLoading} variant="outline" size="sm" className="w-full">
                    Retry build
                  </Button>
                </div>
              )
            )}

            {campaign.status === "failed" && !buildError && (
              <Button onClick={handleBuild} disabled={buildLoading} variant="outline" size="sm" className="mt-3 w-full">
                Retry build
              </Button>
            )}

            {campaign.errors.length > 0 && (
              <div className="mt-4 space-y-1.5 rounded-lg border border-destructive/30 bg-destructive/10 p-3">
                <p className="text-xs font-medium text-destructive">
                  {campaign.errors.length} error{campaign.errors.length > 1 ? "s" : ""} during build
                </p>
                <ul className="space-y-1 text-xs text-destructive/90">
                  {campaign.errors.map((e, i) => (
                    <li key={i} className="break-words">
                      • {e}
                    </li>
                  ))}
                </ul>
              </div>
            )}
          </div>
        </aside>
      </div>
    </div>
  );
}
